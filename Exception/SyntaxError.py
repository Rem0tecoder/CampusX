# Index Error
# The indexError is thrown when trying to access an item at an invalid index

L = [1,2,3,4]
print(L[100])

# Module not found error
import math
math.floor(5.3)

# KeyError
# The KeyError is thrown when a key is not found

d = {'name': 'saurabh', 'age': 20}
print(d['surname'])

# value error
int('a')

# Type error
print(1 + 'a')
