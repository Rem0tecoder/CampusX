# Arithmetic Op
print('Delhi' + 'Mumbai')
print("AB" * 5 )

# Relational Op
print('delhi'=='delhi')
print('mum' > 'pune')
print('Pune' > 'pune')

# Logical Op
print('Hello' and 'World')
print('Hello' or 'World') 
print(not 'hello')

# Loops on Op
for i in 'delhi':
    print(i)


for i in 'mumbai':
    print('pune')

# Membership Op
print('D' in 'Delhi')